-- 1. USERS TABLE (Complete user information)
CREATE TABLE users (
    id UUID DEFAULT gen_random_uuid() PRIMARY KEY,
    created_at TIMESTAMP WITH TIME ZONE DEFAULT NOW(),
    updated_at TIMESTAMP WITH TIME ZONE DEFAULT NOW(),
    
    -- Authentication & Basic Info
    email VARCHAR(255) UNIQUE NOT NULL,
    phone VARCHAR(20) UNIQUE NOT NULL,
    password_hash VARCHAR(255) NOT NULL,
    name VARCHAR(100) NOT NULL,
    security_code VARCHAR(10),
    referral_code VARCHAR(20) UNIQUE NOT NULL,
    referred_by UUID REFERENCES users(id),
    
    -- Account Status & Level
    is_active BOOLEAN DEFAULT TRUE,
    current_level INTEGER DEFAULT 0, -- 0=Recruit, 1=Intern, 2=Job1, etc.
    level_upgraded_at TIMESTAMP WITH TIME ZONE,
    level_investment DECIMAL(10,2) DEFAULT 0.00, -- Amount invested in current level
    
    -- Wallets
    income_wallet DECIMAL(15,2) DEFAULT 0.00,
    recharge_wallet DECIMAL(15,2) DEFAULT 0.00,
    main_wallet DECIMAL(15,2) DEFAULT 0.00,
    wealth_fund_balance DECIMAL(15,2) DEFAULT 0.00,
    
    -- Withdrawal Settings
    withdrawal_account_type VARCHAR(20) CHECK (withdrawal_account_type IN ('mpesa', 'till', 'bank')),
    withdrawal_account_details VARCHAR(100),
    withdrawal_password_hash VARCHAR(255),
    
    -- Daily/Period Tracking
    tasks_completed_today INTEGER DEFAULT 0,
    tasks_reset_date DATE DEFAULT CURRENT_DATE,
    yesterday_earnings DECIMAL(10,2) DEFAULT 0.00,
    today_earnings DECIMAL(10,2) DEFAULT 0.00,
    week_earnings DECIMAL(10,2) DEFAULT 0.00,
    month_earnings DECIMAL(10,2) DEFAULT 0.00,
    total_earnings DECIMAL(15,2) DEFAULT 0.00,
    total_withdrawals DECIMAL(15,2) DEFAULT 0.00,
    referral_rebate_total DECIMAL(10,2) DEFAULT 0.00,
    gift_code_earnings DECIMAL(10,2) DEFAULT 0.00,
    
    -- Metadata
    last_login TIMESTAMP WITH TIME ZONE,
    login_count INTEGER DEFAULT 0,
    device_info JSONB,
    ip_address INET,
    real_balance DECIMAL(15,2) DEFAULT 0.00,
    user_category VARCHAR(20) DEFAULT 'new',
    category_updated_at TIMESTAMP WITH TIME ZONE,
    restrictions JSONB DEFAULT '{}'::jsonb
);

