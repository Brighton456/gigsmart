    apply_to_levels INTEGER[] DEFAULT '{0,1,2,3,4,5,6}',
    
    -- Status & Type
    is_active BOOLEAN DEFAULT TRUE,
    notification_type VARCHAR(30) DEFAULT 'news' CHECK (notification_type IN (
        'news', 'advertisement', 'warning', 'promotion', 'update', 'maintenance'
    )),
    priority INTEGER DEFAULT 1 CHECK (priority BETWEEN 1 AND 5),
    
    -- Content
    icon VARCHAR(50) DEFAULT 'information-circle',
    heading VARCHAR(200) NOT NULL,
    content TEXT NOT NULL,
    image_url VARCHAR(500),
    
    -- Buttons
    button1_text VARCHAR(50) DEFAULT 'OK',
    button1_action VARCHAR(100) DEFAULT 'dismiss',
    button2_text VARCHAR(50),
    button2_action VARCHAR(100),
    
    -- Scheduling
