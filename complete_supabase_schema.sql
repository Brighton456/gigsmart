-- View: Transactions with user info
CREATE VIEW admin_transactions_with_users AS
SELECT 
    t.*, 
    u.name AS user_name,
    u.phone AS user_phone,
    u.email AS user_email
FROM transactions t
JOIN users u ON u.id = t.user_id;

-- View: Investments with user info
CREATE VIEW admin_investments_with_users AS
SELECT 
    i.*, 
    u.name AS user_name,
    u.phone AS user_phone,
    u.email AS user_email
FROM investments i
JOIN users u ON u.id = i.user_id;

-- View: Task completions with user info
CREATE VIEW admin_task_completions_with_users AS
SELECT 
    tc.*, 
    u.name AS user_name,
    u.phone AS user_phone,
    u.email AS user_email
FROM task_completions tc
JOIN users u ON u.id = tc.user_id;

-- View: Spin attempts with user info
CREATE VIEW admin_spin_attempts_with_users AS
SELECT 
    sa.*, 
    u.name AS user_name,
    u.phone AS user_phone,
    u.email AS user_email
FROM spin_attempts sa
JOIN users u ON u.id = sa.user_id;

-- View: Gift code redemptions with user info
CREATE VIEW admin_gift_code_redemptions AS
SELECT 
    gcr.*, 
    u.name AS user_name,
    u.phone AS user_phone,
    u.email AS user_email,
    gc.code AS gift_code
FROM gift_code_redemptions gcr
JOIN users u ON u.id = gcr.user_id
JOIN gift_codes gc ON gc.id = gcr.gift_code_id;

-- View: Referrals with referrer & referred info
CREATE VIEW admin_referrals_with_users AS
SELECT 
    r.*, 
    ref.name AS referrer_name,
    ref.phone AS referrer_phone,
    ref.email AS referrer_email,
    referred.name AS referred_name,
    referred.phone AS referred_phone,
    referred.email AS referred_email
FROM referrals r
JOIN users ref ON ref.id = r.referrer_id
JOIN users referred ON referred.id = r.referred_id;

-- View: User Dashboard Summary
CREATE VIEW admin_user_summary AS
SELECT 
    u.id,
    u.name,
    u.email,
    u.phone,
    u.current_level,
    l.name as level_name,
    u.is_active,
    u.income_wallet,
    u.main_wallet,
    u.wealth_fund_balance,
    u.total_earnings,
    u.total_withdrawals,
    u.tasks_completed_today,
    u.created_at as joined_date,
    u.last_login,
    (SELECT COUNT(*) FROM referrals WHERE referrer_id = u.id) as total_referrals
FROM users u
LEFT JOIN levels l ON u.current_level = l.id;

-- View: Daily Statistics (readable with all identifiers)
CREATE VIEW admin_daily_statistics AS
SELECT 
    ds.stat_date,
    ds.new_users,
    ds.total_users,
    ds.total_deposits,
    ds.total_withdrawals,
    ds.active_task_users,
    ds.total_task_earnings,
    ds.total_referral_earnings,
    ds.total_spin_wins,
    ds.total_gift_code_credits,
    ds.total_investment_volume,
    ds.total_investment_returns
FROM daily_statistics ds
ORDER BY ds.stat_date DESC;

