-- Function to generate daily gift codes
CREATE OR REPLACE FUNCTION generate_daily_gift_codes()
RETURNS void AS $$
BEGIN
    -- Generate 10 random gift codes daily
    INSERT INTO gift_codes (code, reward_type, income_wallet_amount, main_wallet_amount, expires_at)
    SELECT 
        'GIFT' || TO_CHAR(NOW(), 'YYYYMMDD') || LPAD((ROW_NUMBER() OVER())::text, 3, '0'),
        'both_wallets',
        (RANDOM() * 100 + 50)::DECIMAL(10,2),
        (RANDOM() * 200 + 100)::DECIMAL(10,2),
        NOW() + INTERVAL '24 hours'
    FROM generate_series(1, 10);
END;
$$ LANGUAGE plpgsql;

-- Function to reset daily tasks
CREATE OR REPLACE FUNCTION reset_daily_tasks()
RETURNS void AS $$
BEGIN
    UPDATE users 
    SET 
        tasks_completed_today = 0,
        tasks_reset_date = CURRENT_DATE,
        yesterday_earnings = today_earnings,
        today_earnings = 0
    WHERE tasks_reset_date < CURRENT_DATE;
END;
$$ LANGUAGE plpgsql;

-- Function to refresh daily statistics
CREATE OR REPLACE FUNCTION refresh_daily_statistics(target_date DATE DEFAULT CURRENT_DATE)
RETURNS void AS $$
BEGIN
    -- Insert or update daily statistics for the target date
    INSERT INTO daily_statistics (
        stat_date,
        new_users,
        total_users,
        total_deposits,
        total_withdrawals,
        active_task_users,
        total_task_earnings,
        total_referral_earnings,
        total_spin_wins,
        total_gift_code_credits,
        total_investment_volume,
        total_investment_returns,
        updated_at
    )
    SELECT 
        target_date,
        -- New users today
        (SELECT COUNT(*) FROM users WHERE DATE(created_at) = target_date),
        -- Total users up to today
        (SELECT COUNT(*) FROM users WHERE DATE(created_at) <= target_date),
        -- Total deposits today
        (SELECT COALESCE(SUM(amount), 2) FROM transactions 
         WHERE type = 'deposit' AND status = 'completed' AND DATE(created_at) = target_date),
        -- Total withdrawals today
        (SELECT COALESCE(SUM(amount), 0) FROM transactions 
         WHERE type = 'withdrawal' AND status = 'completed' AND DATE(created_at) = target_date),
        -- Active task users today
        (SELECT COUNT(DISTINCT user_id) FROM task_completions WHERE completion_date = target_date),
        -- Total task earnings today
        (SELECT COALESCE(SUM(earnings), 0) FROM task_completions WHERE completion_date = target_date),
        -- Total referral earnings today
        (SELECT COALESCE(SUM(amount), 0) FROM transactions 
         WHERE type = 'referral_bonus' AND status = 'completed' AND DATE(created_at) = target_date),
        -- Total spin wins today
        (SELECT COALESCE(SUM(prize_value), 0) FROM spin_attempts WHERE spin_date = target_date),
        -- Total gift code credits today
        (SELECT COALESCE(SUM(income_wallet_reward + main_wallet_reward), 0) 
         FROM gift_code_redemptions WHERE DATE(redeemed_at) = target_date),
        -- Total investment volume today
        (SELECT COALESCE(SUM(amount), 0) FROM investments WHERE DATE(created_at) = target_date),
        -- Total investment returns today
        (SELECT COALESCE(SUM(amount), 0) FROM transactions 
         WHERE type = 'investment_return' AND status = 'completed' AND DATE(created_at) = target_date),
        NOW()
    ON CONFLICT (stat_date) 
    DO UPDATE SET
        new_users = EXCLUDED.new_users,
        total_users = EXCLUDED.total_users,
        total_deposits = EXCLUDED.total_deposits,
        total_withdrawals = EXCLUDED.total_withdrawals,
        active_task_users = EXCLUDED.active_task_users,
        total_task_earnings = EXCLUDED.total_task_earnings,
        total_referral_earnings = EXCLUDED.total_referral_earnings,
        total_spin_wins = EXCLUDED.total_spin_wins,
        total_gift_code_credits = EXCLUDED.total_gift_code_credits,
        total_investment_volume = EXCLUDED.total_investment_volume,
        total_investment_returns = EXCLUDED.total_investment_returns,
        updated_at = NOW();
END;
$$ LANGUAGE plpgsql;

-- Function to ensure daily statistics record exists for current date
CREATE OR REPLACE FUNCTION ensure_daily_statistics_exists()
RETURNS void AS $$
BEGIN
    -- Create today's record if it doesn't exist
    INSERT INTO daily_statistics (stat_date)
    VALUES (CURRENT_DATE)
    ON CONFLICT (stat_date) DO NOTHING;
    
    -- Refresh today's statistics
    PERFORM refresh_daily_statistics(CURRENT_DATE);
END;
$$ LANGUAGE plpgsql;

