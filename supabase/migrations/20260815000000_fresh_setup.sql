-- Update user stats when transactions are added
CREATE OR REPLACE FUNCTION update_user_stats()
RETURNS TRIGGER AS $$
BEGIN
    IF NEW.status = 'completed' THEN
        UPDATE users SET
            total_earnings = total_earnings + CASE WHEN NEW.amount > 0 THEN NEW.amount ELSE 0 END,
            total_withdrawals = total_withdrawals + CASE WHEN NEW.type = 'withdrawal' THEN NEW.amount ELSE 0 END,
            today_earnings = today_earnings + CASE WHEN NEW.amount > 0 AND DATE(NEW.created_at) = CURRENT_DATE THEN NEW.amount ELSE 0 END,
            updated_at = NOW()
        WHERE id = NEW.user_id;
        
        -- Refresh daily statistics
        PERFORM ensure_daily_statistics_exists();
    END IF;
    RETURN NEW;
END;
$$ LANGUAGE plpgsql;

